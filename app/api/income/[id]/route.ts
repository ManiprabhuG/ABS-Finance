import { NextResponse } from 'next/server';
import { db } from '@/lib/db';
import { getSession } from '@/lib/auth';

export async function GET(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const income = await db.income.findUnique({ where: { id } });
    if (!income) return NextResponse.json({ error: 'Income record not found' }, { status: 404 });
    return NextResponse.json(income);
  } catch (error: any) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}

export async function PUT(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const session = await getSession();
    const data = await request.json();

    const updated = await db.income.update({
      where: { id },
      data: {
        category: data.category,
        amount: parseFloat(data.amount),
        paymentMode: data.paymentMode,
        remarks: data.remarks || null,
      },
    });

    await db.auditLog.create({
      data: {
        userId: session?.id,
        username: session?.username || 'System',
        action: 'UPDATE',
        module: 'FINANCE',
        details: `Updated income entry ${updated.incomeNo}`,
      },
    });

    return NextResponse.json(updated);
  } catch (error: any) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}

export async function DELETE(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const session = await getSession();

    const inc = await db.income.findUnique({ where: { id } });
    if (!inc) return NextResponse.json({ error: 'Income record not found' }, { status: 404 });

    await db.income.delete({ where: { id } });

    await db.auditLog.create({
      data: {
        userId: session?.id,
        username: session?.username || 'System',
        action: 'DELETE',
        module: 'FINANCE',
        details: `Deleted income entry ${inc.incomeNo}`,
      },
    });

    return NextResponse.json({ success: true });
  } catch (error: any) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}
